/** Pixel scale drawBanner uses for a frame of this height (about 1/40 of the height per line). */
inline int bannerScale(int frameHeight) { return std::max(1, frameHeight / 360); }
/** Size of the box drawBanner draws at scale s. */
inline void bannerSize(const std::vector<std::string>& lines, int s, int& w, int& h) {
  size_t longest = 0;
  for (const auto& l : lines) longest = std::max(longest, l.size());
  w = int(longest) * 6 * s + 4 * s;
  h = int(lines.size()) * 9 * s + 4 * s;
}

/** Draws `lines` top left on an opaque black box. Character cell 6x9 font pixels times `scale`
 *  (default: bannerScale(img.height)). Clipped to the image. */
inline void drawBanner(Image& img, const std::vector<std::string>& lines, int scale = 0) {
  if (img.width <= 0 || img.height <= 0 || lines.empty()) return;
  const int s = scale > 0 ? scale : bannerScale(img.height);
  size_t longest = 0;
  for (const auto& l : lines) longest = std::max(longest, l.size());
  const int pad = 2 * s, boxW = int(longest) * 6 * s + 2 * pad, boxH = int(lines.size()) * 9 * s + 2 * pad;
  for (int y = 0; y < std::min(boxH, img.height); ++y)
    for (int x = 0; x < std::min(boxW, img.width); ++x) {
      float* p = img.at(x, y);
      p[0] = p[1] = p[2] = 0.0f;
      p[3] = 1.0f;  // opaque, so the text is visible on transparent layers too
    }
  for (size_t li = 0; li < lines.size(); ++li)
    for (size_t ci = 0; ci < lines[li].size(); ++ci) {
      const unsigned char* g = glyph(lines[li][ci]);
      for (int gy = 0; gy < 7; ++gy)
        for (int gx = 0; gx < 5; ++gx) {
          if (!(g[gy] & (0x10 >> gx))) continue;
          for (int sy = 0; sy < s; ++sy)
            for (int sx = 0; sx < s; ++sx) {
              const int x = pad + (int(ci) * 6 + gx) * s + sx, y = pad + (int(li) * 9 + gy) * s + sy;
              if (x < img.width && y < img.height) {
                float* p = img.at(x, y);
                p[0] = p[1] = p[2] = 1.0f;
              }
            }
        }
    }
}

